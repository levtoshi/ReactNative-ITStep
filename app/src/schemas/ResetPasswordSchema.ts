import { z } from "zod"

// Правила для форми «Новий пароль»
export const ResetPasswordSchema = z
    .object({
        // Коректний email
        email:
            z.email("Вкажіть правильно пошту"),
        // Код із листа: рівно 6 цифр (^ — початок, \d{6} — шість цифр, $ — кінець)
        code:
            z.string().regex(/^\d{6}$/, "Код має складатися з 6 цифр"),
        // Новий пароль не коротший за 6 символів (так само, як вимагає сервер)
        newPassword:
            z.string().min(6, "Пароль має бути мін 6 символів"),
    });
